-- VIDE LES DONNEES DU SCHEMA CINEMA SANS SUPPRIMER LES TABLES, VUES OU FONCTIONS.
-- ATTENTION : les donnees applicatives existantes seront effacees.
-- Utiliser uniquement dans le schema dedie CINEMA.
-- Apres ce script, cinema-application-data.sql peut etre execute pour
-- recharger les categories, les donnees de demonstration et le menu.
SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_schema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
BEGIN
    IF v_schema <> 'CINEMA' THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Connecte-toi au schema CINEMA avant de lancer ce script. Schema courant: ' || v_schema);
    END IF;
END;
/

-- Donnees de navigation et droits ajoutes par l'application Cinema.
DELETE FROM USERMENU WHERE ID LIKE 'CINEMAUSR%';
DELETE FROM MENUDYNAMIQUE WHERE ID LIKE 'CINEMA%' AND ID_PERE IS NOT NULL;
DELETE FROM MENUDYNAMIQUE WHERE ID LIKE 'CINEMA%';
DELETE FROM ACTIONROLE WHERE ID LIKE 'CINEMA-ACT-PAY-%' OR ID LIKE 'CINEMA-ACT-CREATE-%';

-- Donnees metier : enfants avant parents pour respecter les cles etrangeres.
DELETE FROM CINE_BILLET;
DELETE FROM LIAISONPAIEMENT;
UPDATE MVTCAISSE SET IDMVTCAISSE_ORIGINE = NULL;
DELETE FROM MVTCAISSE;
DELETE FROM FACTURECLIENT_LIGNE;
DELETE FROM CINE_PAIEMENT;
DELETE FROM VENTEDETAILS;
DELETE FROM VENTE;
DELETE FROM CINE_RESERVATION_PLACE;
DELETE FROM CINE_RESERVATION_DETAIL;
DELETE FROM CINE_RESERVATION;
DELETE FROM FACTURECLIENT WHERE TYPE_DOCUMENT = 'AVOIR';
DELETE FROM FACTURECLIENT;
DELETE FROM CINE_SEANCE;
DELETE FROM CINE_PLACE;
DELETE FROM CINE_SALLE;
DELETE FROM CINE_FILM;
DELETE FROM CINE_CATEGORIE_PLACE;
DELETE FROM CLIENT;
DELETE FROM MODEPAIEMENT;
DELETE FROM CAISSE;

-- Les identifiants de demonstration sont fixes. Repositionner les sequences
-- apres ces numeros pour eviter une collision lors des prochaines creations.
ALTER SEQUENCE SEQ_CLIENT RESTART START WITH 4;
ALTER SEQUENCE SEQ_MODEPAIEMENT RESTART START WITH 4;
ALTER SEQUENCE SEQ_CAISSE RESTART START WITH 2;
ALTER SEQUENCE SEQ_CINE_CATEGORIE_PLACE RESTART START WITH 3;
ALTER SEQUENCE SEQ_CINE_SALLE RESTART START WITH 3;
ALTER SEQUENCE SEQ_CINE_PLACE RESTART START WITH 11;
ALTER SEQUENCE SEQ_CINE_FILM RESTART START WITH 4;
ALTER SEQUENCE SEQ_CINE_SEANCE RESTART START WITH 4;
ALTER SEQUENCE SEQ_CINE_RESERVATION RESTART START WITH 1;
ALTER SEQUENCE SEQ_CINE_RESERVATION_DETAIL RESTART START WITH 1;
ALTER SEQUENCE SEQ_CINE_RESERVATION_PLACE RESTART START WITH 1;
ALTER SEQUENCE SEQ_VENTE RESTART START WITH 1;
ALTER SEQUENCE SEQ_VENTEDETAILS RESTART START WITH 1;
ALTER SEQUENCE SEQ_FACTURECLIENT RESTART START WITH 1;
ALTER SEQUENCE SEQ_FACTURECLIENT_LIGNE RESTART START WITH 1;
ALTER SEQUENCE SEQ_CINE_PAIEMENT RESTART START WITH 1;
ALTER SEQUENCE SEQ_LIAISONPAIEMENT RESTART START WITH 1;
ALTER SEQUENCE SEQ_MVTCAISSE RESTART START WITH 1;
ALTER SEQUENCE SEQ_CINE_BILLET RESTART START WITH 1;

COMMIT;
PROMPT Donnees du schema CINEMA effacees; les objets du schema sont conserves.
