CREATE TABLE CLIENT (
    IDCLIENT            VARCHAR2(20)   NOT NULL,
    CODECLIENT          VARCHAR2(20)   NOT NULL,
    NOM                 VARCHAR2(80)   NOT NULL,
    PRENOM              VARCHAR2(80),
    EMAIL               VARCHAR2(120),
    TELEPHONE           VARCHAR2(30),
    ACTIF               NUMBER(1)      DEFAULT 1 NOT NULL,
    DATYCREATION        DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CLIENT PRIMARY KEY (IDCLIENT),
    CONSTRAINT UK_CLIENT_CODE UNIQUE (CODECLIENT),
    CONSTRAINT CK_CLIENT_ACTIF CHECK (ACTIF IN (0, 1))
);

