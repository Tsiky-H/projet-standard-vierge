-- Supprime les colonnes de code redondantes des tables métier Cinema.
-- Les identifiants primaires et les données associées sont conservés.
-- Les colonnes de code techniques du framework APJ (CODESERVICE, CODEDIR, etc.)
-- ne font pas partie de cette migration.
SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

DECLARE
    v_schema VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
    v_count NUMBER;
BEGIN
    IF v_schema <> 'CINEMA' THEN
        RAISE_APPLICATION_ERROR(-20001,
            'Connecte-toi au schema CINEMA avant de lancer ce script. Schema courant: ' || v_schema);
    END IF;

    FOR colonne IN (
        SELECT 'CLIENT' TABLE_NAME, 'CODECLIENT' COLUMN_NAME FROM DUAL UNION ALL
        SELECT 'MODEPAIEMENT', 'CODE' FROM DUAL UNION ALL
        SELECT 'CAISSE', 'CODE' FROM DUAL UNION ALL
        SELECT 'CINE_CATEGORIE_PLACE', 'CODE' FROM DUAL UNION ALL
        SELECT 'CINE_SALLE', 'CODE' FROM DUAL UNION ALL
        SELECT 'CINE_FILM', 'CODE' FROM DUAL
    ) LOOP
        SELECT COUNT(*) INTO v_count
        FROM USER_TAB_COLUMNS
        WHERE TABLE_NAME = colonne.TABLE_NAME
          AND COLUMN_NAME = colonne.COLUMN_NAME;

        IF v_count > 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || colonne.TABLE_NAME
                || ' DROP COLUMN ' || colonne.COLUMN_NAME || ' CASCADE CONSTRAINTS';
        END IF;
    END LOOP;
END;
/

CREATE OR REPLACE VIEW CINE_CATEGORIE_PLACE_LIB AS
SELECT cp.IDCATEGORIEPLACE, cp.LIBELLE, cp.PRIX_BASE, cp.ACTIF
FROM CINE_CATEGORIE_PLACE cp;

CREATE OR REPLACE VIEW CINE_SALLE_LIB AS
SELECT s.IDSALLE, s.LIBELLE, s.CAPACITE, s.ACTIF,
       NVL(p.NOMBRE_PLACES, 0) AS NOMBRE_PLACES
FROM CINE_SALLE s
LEFT JOIN (
    SELECT IDSALLE, COUNT(*) AS NOMBRE_PLACES
    FROM CINE_PLACE
    GROUP BY IDSALLE
) p ON p.IDSALLE = s.IDSALLE;

CREATE OR REPLACE VIEW CINE_FILM_LIB AS
SELECT f.IDFILM, f.TITRE, f.DUREE_MINUTES, f.CLASSIFICATION_AGE, f.ACTIF
FROM CINE_FILM f;

MERGE INTO ACTIONROLE cible
USING (
    SELECT 'CINEMA-ACT-CREATE-001' ID, 'CINE_FILM' NOMTABLEOBJET FROM DUAL
    UNION ALL SELECT 'CINEMA-ACT-CREATE-002', 'CINE_SALLE' FROM DUAL
    UNION ALL SELECT 'CINEMA-ACT-CREATE-003', 'CINE_PLACE' FROM DUAL
    UNION ALL SELECT 'CINEMA-ACT-CREATE-004', 'CINE_SEANCE' FROM DUAL
) source
ON (cible.ID = source.ID)
WHEN MATCHED THEN UPDATE SET cible.NOMTABLEOBJET=source.NOMTABLEOBJET,
    cible.ACTION='insert', cible.ROLEMINIMUM=9, cible.DIRECTION=NULL,
    cible.UTILISATEUR=NULL, cible.GROUPETABLE=NULL
WHEN NOT MATCHED THEN INSERT
    (ID, NOMTABLEOBJET, ACTION, ROLEMINIMUM, DIRECTION, UTILISATEUR, GROUPETABLE)
    VALUES (source.ID, source.NOMTABLEOBJET, 'insert', 9, NULL, NULL, NULL);

COMMIT;
PROMPT Colonnes CODE métier supprimées; identifiants et données conservés.
