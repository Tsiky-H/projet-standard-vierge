    PROCEDURE drop_existing(p_type IN VARCHAR2, p_name IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE 'DROP ' || p_type || ' "' || p_name || '"'
            || CASE WHEN p_type = 'TABLE' THEN ' CASCADE CONSTRAINTS PURGE' ELSE '' END;
    EXCEPTION
        WHEN OTHERS THEN
            IF (p_type = 'TABLE' AND SQLCODE = -942)
               OR (p_type = 'VIEW' AND SQLCODE = -942)
               OR (p_type = 'FUNCTION' AND SQLCODE = -4043)
               OR (p_type = 'SEQUENCE' AND SQLCODE = -2289) THEN
                NULL;
            ELSE
                RAISE;
            END IF;
    END;
BEGIN
    IF SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') <> 'CINEMA' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Connecte-toi au schema CINEMA avant de lancer ce script.');
    END IF;

    FOR i IN 1 .. v_views.COUNT LOOP
        drop_existing('VIEW', v_views(i));
    END LOOP;
    FOR i IN 1 .. v_functions.COUNT LOOP
        drop_existing('FUNCTION', v_functions(i));
    END LOOP;
    FOR i IN 1 .. v_tables.COUNT LOOP
        drop_existing('TABLE', v_tables(i));
    END LOOP;
    FOR i IN 1 .. v_sequences.COUNT LOOP
        drop_existing('SEQUENCE', v_sequences(i));
    END LOOP;
END;
