-- Disponibilite des seances et des places pour la vente directe jusqu'a la fin.
SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK

CREATE OR REPLACE VIEW CINE_SEANCE_VENDABLE AS
SELECT se.IDSEANCE, se.IDFILM, se.IDFILMLIB, se.IDSALLE, se.IDSALLELIB,
       se.DATEHEURE_DEBUT, se.DATEHEURE_FIN, se.STATUT, se.LIBELLE_SEANCE
FROM CINE_SEANCE_LIB se
WHERE se.STATUT IN ('PLANIFIEE', 'OUVERTE')
  AND se.DATEHEURE_FIN > SYSDATE
  AND se.IDFILM IN (SELECT IDFILM FROM CINE_FILM WHERE ACTIF = 1)
  AND se.IDSALLE IN (SELECT IDSALLE FROM CINE_SALLE WHERE ACTIF = 1);

CREATE OR REPLACE VIEW CINE_PLACE_SEANCE_DISPO AS
SELECT se.IDSEANCE, p.IDPLACE, p.IDSALLE, sa.LIBELLE AS IDSALLELIB,
       se.IDFILM, f.TITRE AS IDFILMLIB, se.DATEHEURE_DEBUT, se.DATEHEURE_FIN,
       p.NUMERO, p.RANGEE, p.IDCATEGORIEPLACE,
       cp.LIBELLE AS IDCATEGORIEPLACELIB, cp.PRIX_BASE, p.ACTIF,
       CASE WHEN rp.IDRESERVATION_PLACE IS NOT NULL THEN 'RESERVATION'
            WHEN vd.IDVENTEDETAILS IS NOT NULL THEN 'VENTE' ELSE NULL END AS SOURCE_BLOCAGE,
       CASE WHEN rp.IDRESERVATION_PLACE IS NOT NULL THEN 'BLOQUEE'
            WHEN vd.IDVENTEDETAILS IS NOT NULL THEN vd.STATUT
            WHEN p.ACTIF = 1 AND cp.ACTIF = 1
             AND se.STATUT IN ('PLANIFIEE', 'OUVERTE') AND se.DATEHEURE_FIN > SYSDATE
            THEN 'DISPONIBLE' ELSE 'INDISPONIBLE' END AS STATUT_OCCUPATION,
       CASE WHEN p.ACTIF = 1 AND cp.ACTIF = 1
             AND se.STATUT IN ('PLANIFIEE', 'OUVERTE') AND se.DATEHEURE_FIN > SYSDATE
             AND rp.IDRESERVATION_PLACE IS NULL AND vd.IDVENTEDETAILS IS NULL
            THEN 1 ELSE 0 END AS DISPONIBLE
FROM CINE_SEANCE se
JOIN CINE_FILM f ON f.IDFILM = se.IDFILM
JOIN CINE_SALLE sa ON sa.IDSALLE = se.IDSALLE
JOIN CINE_PLACE p ON p.IDSALLE = se.IDSALLE
JOIN CINE_CATEGORIE_PLACE cp ON cp.IDCATEGORIEPLACE = p.IDCATEGORIEPLACE
LEFT JOIN CINE_RESERVATION_PLACE rp ON rp.IDSEANCE = se.IDSEANCE AND rp.IDPLACE = p.IDPLACE
 AND rp.STATUT IN ('BLOQUEE', 'ACHETEE')
LEFT JOIN VENTEDETAILS vd ON vd.IDSEANCE = se.IDSEANCE AND vd.IDPLACE = p.IDPLACE
 AND vd.STATUT IN ('BLOQUEE', 'ACHETEE');

PROMPT Vue CINE_SEANCE_VENDABLE et disponibilite adaptees a l'achat direct.
