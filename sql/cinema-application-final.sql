-- ============================================================================
-- 3) Reservation (mere/detail/place)
-- ============================================================================
CREATE TABLE CINE_RESERVATION (
    IDRESERVATION           VARCHAR2(20)   NOT NULL,
    IDCLIENT                VARCHAR2(20)   NOT NULL,
    IDMODEPAIEMENT_PREVU    VARCHAR2(20),
    DATE_RESERVATION        DATE           DEFAULT SYSDATE NOT NULL,
    DATE_EXPIRATION         DATE           NOT NULL,
    STATUT                  VARCHAR2(20)   DEFAULT 'EN_ATTENTE' NOT NULL,
    NB_PLACES_TOTAL         NUMBER(6)      DEFAULT 0 NOT NULL,
    MONTANT_TOTAL           NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    REMARQUE                VARCHAR2(500),
    CONSTRAINT PK_CINE_RESERVATION PRIMARY KEY (IDRESERVATION),
    CONSTRAINT CK_CINE_RES_STATUT CHECK (STATUT IN ('EN_ATTENTE', 'CONFIRMEE', 'EXPIREE', 'ANNULEE')),
    CONSTRAINT CK_CINE_RES_NB_PLACES CHECK (NB_PLACES_TOTAL >= 0),
    CONSTRAINT CK_CINE_RES_MONTANT CHECK (MONTANT_TOTAL >= 0),
    CONSTRAINT CK_CINE_RES_DATES CHECK (DATE_EXPIRATION >= DATE_RESERVATION),
    CONSTRAINT FK_CINE_RES_CLIENT FOREIGN KEY (IDCLIENT)
        REFERENCES CLIENT (IDCLIENT),
    CONSTRAINT FK_CINE_RES_MODEPAYE FOREIGN KEY (IDMODEPAIEMENT_PREVU)
        REFERENCES MODEPAIEMENT (IDMODEPAIEMENT)
);

CREATE TABLE CINE_RESERVATION_DETAIL (
    IDRESERVATION_DETAIL    VARCHAR2(20)   NOT NULL,
    IDRESERVATION           VARCHAR2(20)   NOT NULL,
    IDSEANCE                VARCHAR2(20)   NOT NULL,
    NB_PLACES               NUMBER(6)      NOT NULL,
    MONTANT_LIGNE           NUMBER(14, 2)  NOT NULL,
    STATUT                  VARCHAR2(20)   DEFAULT 'EN_ATTENTE' NOT NULL,
    CONSTRAINT PK_CINE_RESERVATION_DETAIL PRIMARY KEY (IDRESERVATION_DETAIL),
    CONSTRAINT CK_CINE_RESD_NB_PLACES CHECK (NB_PLACES > 0),
    CONSTRAINT CK_CINE_RESD_MONTANT CHECK (MONTANT_LIGNE >= 0),
    CONSTRAINT CK_CINE_RESD_STATUT CHECK (STATUT IN ('EN_ATTENTE', 'CONFIRMEE', 'EXPIREE', 'ANNULEE')),
    CONSTRAINT FK_CINE_RESD_RES FOREIGN KEY (IDRESERVATION)
        REFERENCES CINE_RESERVATION (IDRESERVATION),
    CONSTRAINT FK_CINE_RESD_SEANCE FOREIGN KEY (IDSEANCE)
        REFERENCES CINE_SEANCE (IDSEANCE)
);

CREATE INDEX IDX_CINE_RESD_RES ON CINE_RESERVATION_DETAIL (IDRESERVATION);
CREATE INDEX IDX_CINE_RESD_SEANCE ON CINE_RESERVATION_DETAIL (IDSEANCE);

CREATE TABLE CINE_RESERVATION_PLACE (
    IDRESERVATION_PLACE     VARCHAR2(20)   NOT NULL,
    IDRESERVATION_DETAIL    VARCHAR2(20)   NOT NULL,
    IDSEANCE                VARCHAR2(20)   NOT NULL,
    IDPLACE                 VARCHAR2(20)   NOT NULL,
    IDCATEGORIEPLACE        VARCHAR2(20)   NOT NULL,
    PRIX_INITIAL            NUMBER(12, 2)  NOT NULL,
    TAUX_REMISE             NUMBER(5, 2)   DEFAULT 0 NOT NULL,
    IDREMISE_APPLIQUEE      VARCHAR2(20),
    MONTANT_REMISE          NUMBER(12, 2)  DEFAULT 0 NOT NULL,
    PRIX_UNITAIRE           NUMBER(12, 2)  NOT NULL,
    STATUT                  VARCHAR2(20)   DEFAULT 'BLOQUEE' NOT NULL,
    DATE_BLOCAGE            DATE           DEFAULT SYSDATE NOT NULL,
    DATE_EXPIRATION         DATE           NOT NULL,
    DATE_VALIDATION         DATE,
    CONSTRAINT PK_CINE_RESERVATION_PLACE PRIMARY KEY (IDRESERVATION_PLACE),
    CONSTRAINT UK_CINE_RESPR_DET_PLACE UNIQUE (IDRESERVATION_DETAIL, IDPLACE),
    CONSTRAINT CK_CINE_RESPR_PRIX CHECK (
        PRIX_INITIAL >= 0 AND PRIX_UNITAIRE >= 0
        AND TAUX_REMISE >= 0 AND TAUX_REMISE <= 100
        AND MONTANT_REMISE >= 0
        AND PRIX_UNITAIRE = PRIX_INITIAL - MONTANT_REMISE
    ),
    CONSTRAINT CK_CINE_RESPR_STATUT CHECK (STATUT IN ('BLOQUEE', 'ACHETEE', 'EXPIREE', 'ANNULEE')),
    CONSTRAINT CK_CINE_RESPR_DATES CHECK (DATE_EXPIRATION >= DATE_BLOCAGE),
    CONSTRAINT FK_CINE_RESPR_DETAIL FOREIGN KEY (IDRESERVATION_DETAIL)
        REFERENCES CINE_RESERVATION_DETAIL (IDRESERVATION_DETAIL),
    CONSTRAINT FK_CINE_RESPR_SEANCE FOREIGN KEY (IDSEANCE)
        REFERENCES CINE_SEANCE (IDSEANCE),
    CONSTRAINT FK_CINE_RESPR_PLACE FOREIGN KEY (IDPLACE)
        REFERENCES CINE_PLACE (IDPLACE),
    CONSTRAINT FK_CINE_RESPR_CATEGORIE FOREIGN KEY (IDCATEGORIEPLACE)
        REFERENCES CINE_CATEGORIE_PLACE (IDCATEGORIEPLACE),
    CONSTRAINT FK_CINE_RESPR_REMISE FOREIGN KEY (IDREMISE_APPLIQUEE)
        REFERENCES REMISE (ID)
);

-- Une place ne peut etre reservee qu'une fois tant qu'elle est BLOQUEE ou ACHETEE.
-- Les reservations EXPIREE ou ANNULEE liberent la place pour une nouvelle reservation.
CREATE UNIQUE INDEX UK_CINE_RESPR_SEANCE_PLACE ON CINE_RESERVATION_PLACE (
    CASE WHEN STATUT IN ('BLOQUEE', 'ACHETEE') THEN IDSEANCE END,
    CASE WHEN STATUT IN ('BLOQUEE', 'ACHETEE') THEN IDPLACE END
);

CREATE INDEX IDX_CINE_RESPR_DETAIL ON CINE_RESERVATION_PLACE (IDRESERVATION_DETAIL);
CREATE INDEX IDX_CINE_RESPR_SEANCE ON CINE_RESERVATION_PLACE (IDSEANCE);

-- ============================================================================
-- 4) Vente, facture, paiement, caisse
-- ============================================================================
CREATE TABLE FACTURECLIENT (
    IDFACTURECLIENT      VARCHAR2(20)   NOT NULL,
    NUMERO_FACTURE       VARCHAR2(30)   NOT NULL,
    TYPE_DOCUMENT        VARCHAR2(20)   DEFAULT 'FACTURE' NOT NULL,
    IDFACTURE_ORIGINE    VARCHAR2(20),
    IDCLIENT             VARCHAR2(20)   NOT NULL,
    DATY                 DATE           DEFAULT SYSDATE NOT NULL,
    STATUT               VARCHAR2(20)   DEFAULT 'BROUILLON' NOT NULL,
    ETAT                 NUMBER(4)      DEFAULT 1 NOT NULL,
    MONTANT_HT           NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    MONTANT_TVA          NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    MONTANT_TTC          NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FACTURECLIENT PRIMARY KEY (IDFACTURECLIENT),
    CONSTRAINT UK_FACTURECLIENT_NUM UNIQUE (NUMERO_FACTURE),
    CONSTRAINT CK_FACT_TYPE CHECK (TYPE_DOCUMENT IN ('FACTURE', 'AVOIR')),
    CONSTRAINT CK_FACT_ORIGINE CHECK (
        (TYPE_DOCUMENT = 'FACTURE' AND IDFACTURE_ORIGINE IS NULL)
        OR (TYPE_DOCUMENT = 'AVOIR' AND IDFACTURE_ORIGINE IS NOT NULL)
    ),
    CONSTRAINT CK_FACT_STATUT CHECK (STATUT IN ('BROUILLON', 'PAYEE', 'ANNULEE', 'REMBOURSEE')),
    CONSTRAINT CK_FACT_MONTANTS CHECK (
        MONTANT_HT >= 0 AND MONTANT_TVA >= 0 AND MONTANT_TTC >= 0 AND MONTANT_TTC = MONTANT_HT + MONTANT_TVA
    ),
    CONSTRAINT FK_FACT_CLIENT FOREIGN KEY (IDCLIENT)
        REFERENCES CLIENT (IDCLIENT),
    CONSTRAINT FK_FACT_ORIGINE FOREIGN KEY (IDFACTURE_ORIGINE)
        REFERENCES FACTURECLIENT (IDFACTURECLIENT)
);

CREATE TABLE FACTURECLIENT_LIGNE (
    IDFACTURECLIENT_LIGNE  VARCHAR2(20)   NOT NULL,
    IDFACTURECLIENT        VARCHAR2(20)   NOT NULL,
    DESIGNATION            VARCHAR2(250)  NOT NULL,
    QUANTITE               NUMBER(10, 2)  NOT NULL,
    PRIX_UNITAIRE          NUMBER(12, 2)  NOT NULL,
    TAUX_TVA               NUMBER(5, 2)   DEFAULT 0 NOT NULL,
    MONTANT_HT             NUMBER(14, 2)  NOT NULL,
    MONTANT_TVA            NUMBER(14, 2)  NOT NULL,
    MONTANT_TTC            NUMBER(14, 2)  NOT NULL,
    ETAT                   NUMBER(4)      DEFAULT 1 NOT NULL,
    IDRESERVATION_PLACE    VARCHAR2(20),
    IDVENTEDETAILS         VARCHAR2(20),
    IDFACTURECLIENT_LIGNE_ORIGINE VARCHAR2(20),
    CONSTRAINT PK_FACTURECLIENT_LIGNE PRIMARY KEY (IDFACTURECLIENT_LIGNE),
    CONSTRAINT CK_FACTL_QTE CHECK (QUANTITE > 0),
    CONSTRAINT CK_FACTL_PRIX CHECK (PRIX_UNITAIRE >= 0),
    CONSTRAINT CK_FACTL_TVA CHECK (TAUX_TVA >= 0),
    CONSTRAINT CK_FACTL_MONTANTS CHECK (
        MONTANT_HT >= 0 AND MONTANT_TVA >= 0 AND MONTANT_TTC >= 0 AND MONTANT_TTC = MONTANT_HT + MONTANT_TVA
    ),
    CONSTRAINT CK_FACTL_SOURCE CHECK (
        (IDFACTURECLIENT_LIGNE_ORIGINE IS NOT NULL AND IDRESERVATION_PLACE IS NULL AND IDVENTEDETAILS IS NULL)
        OR (IDFACTURECLIENT_LIGNE_ORIGINE IS NULL AND
            ((IDRESERVATION_PLACE IS NOT NULL AND IDVENTEDETAILS IS NULL)
             OR (IDRESERVATION_PLACE IS NULL AND IDVENTEDETAILS IS NOT NULL)))
    ),
    CONSTRAINT FK_FACTL_FACT FOREIGN KEY (IDFACTURECLIENT)
        REFERENCES FACTURECLIENT (IDFACTURECLIENT),
    CONSTRAINT FK_FACTL_RESPR FOREIGN KEY (IDRESERVATION_PLACE)
        REFERENCES CINE_RESERVATION_PLACE (IDRESERVATION_PLACE),
    CONSTRAINT FK_FACTL_ORIGINE FOREIGN KEY (IDFACTURECLIENT_LIGNE_ORIGINE)
        REFERENCES FACTURECLIENT_LIGNE (IDFACTURECLIENT_LIGNE)
);

CREATE INDEX IDX_FACTL_FACTURE ON FACTURECLIENT_LIGNE (IDFACTURECLIENT);

CREATE TABLE VENTE (
    IDVENTE               VARCHAR2(20)   NOT NULL,
    DATY                  DATE           DEFAULT SYSDATE NOT NULL,
    TYPE_VENTE            VARCHAR2(20)   NOT NULL,
    STATUT                VARCHAR2(20)   DEFAULT 'BROUILLON' NOT NULL,
    IDCLIENT              VARCHAR2(20)   NOT NULL,
    IDCAISSE              VARCHAR2(20),
    IDRESERVATION         VARCHAR2(20),
    IDFACTURECLIENT       VARCHAR2(20),
    MONTANT_TOTAL         NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    CONSTRAINT PK_VENTE PRIMARY KEY (IDVENTE),
    CONSTRAINT CK_VENTE_TYPE CHECK (TYPE_VENTE IN ('DIRECTE', 'RESERVATION')),
    CONSTRAINT CK_VENTE_STATUT CHECK (STATUT IN ('BROUILLON', 'VALIDEE', 'ANNULEE')),
    CONSTRAINT CK_VENTE_MONTANT CHECK (MONTANT_TOTAL >= 0),
    CONSTRAINT CK_VENTE_SOURCE CHECK (
        (TYPE_VENTE = 'DIRECTE' AND IDRESERVATION IS NULL)
        OR (TYPE_VENTE = 'RESERVATION' AND IDRESERVATION IS NOT NULL)
    ),
    CONSTRAINT CK_VENTE_CAISSE CHECK (
        IDCAISSE IS NOT NULL
        OR (TYPE_VENTE = 'RESERVATION' AND STATUT IN ('BROUILLON', 'ANNULEE'))
    ),
    CONSTRAINT FK_VENTE_CLIENT FOREIGN KEY (IDCLIENT)
        REFERENCES CLIENT (IDCLIENT),
    CONSTRAINT FK_VENTE_CAISSE FOREIGN KEY (IDCAISSE)
        REFERENCES CAISSE (IDCAISSE),
    CONSTRAINT FK_VENTE_RES FOREIGN KEY (IDRESERVATION)
        REFERENCES CINE_RESERVATION (IDRESERVATION),
    CONSTRAINT FK_VENTE_FACT FOREIGN KEY (IDFACTURECLIENT)
        REFERENCES FACTURECLIENT (IDFACTURECLIENT)
);

CREATE UNIQUE INDEX UK_VENTE_RESERVATION ON VENTE (IDRESERVATION);

CREATE TABLE VENTEDETAILS (
    IDVENTEDETAILS        VARCHAR2(20)   NOT NULL,
    IDVENTE               VARCHAR2(20)   NOT NULL,
    IDSEANCE              VARCHAR2(20)   NOT NULL,
    IDPLACE               VARCHAR2(20)   NOT NULL,
    IDCATEGORIEPLACE      VARCHAR2(20)   NOT NULL,
    DESIGNATION           VARCHAR2(250)  NOT NULL,
    QUANTITE              NUMBER(10, 2)  DEFAULT 1 NOT NULL,
    PRIX_INITIAL          NUMBER(12, 2)  NOT NULL,
    TAUX_REMISE           NUMBER(5, 2)   DEFAULT 0 NOT NULL,
    IDREMISE_APPLIQUEE    VARCHAR2(20),
    MONTANT_REMISE        NUMBER(12, 2)  DEFAULT 0 NOT NULL,
    PRIX_UNITAIRE         NUMBER(12, 2)  NOT NULL,
    MONTANT_LIGNE         NUMBER(14, 2)  NOT NULL,
    STATUT                VARCHAR2(20)   DEFAULT 'BLOQUEE' NOT NULL,
    CONSTRAINT PK_VENTEDETAILS PRIMARY KEY (IDVENTEDETAILS),
    CONSTRAINT CK_VD_QTE CHECK (QUANTITE > 0),
    CONSTRAINT CK_VD_PRIX CHECK (
        PRIX_INITIAL >= 0 AND PRIX_UNITAIRE >= 0
        AND TAUX_REMISE >= 0 AND TAUX_REMISE <= 100
        AND MONTANT_REMISE >= 0
        AND PRIX_UNITAIRE = PRIX_INITIAL - MONTANT_REMISE
        AND MONTANT_LIGNE = PRIX_UNITAIRE * QUANTITE
    ),
    CONSTRAINT CK_VD_MONTANT CHECK (MONTANT_LIGNE >= 0),
    CONSTRAINT CK_VD_STATUT CHECK (STATUT IN ('BLOQUEE', 'ACHETEE', 'ANNULEE')),
    CONSTRAINT FK_VD_VENTE FOREIGN KEY (IDVENTE)
        REFERENCES VENTE (IDVENTE),
    CONSTRAINT FK_VD_SEANCE FOREIGN KEY (IDSEANCE)
        REFERENCES CINE_SEANCE (IDSEANCE),
    CONSTRAINT FK_VD_PLACE FOREIGN KEY (IDPLACE)
        REFERENCES CINE_PLACE (IDPLACE),
    CONSTRAINT FK_VD_CATEGORIE FOREIGN KEY (IDCATEGORIEPLACE)
        REFERENCES CINE_CATEGORIE_PLACE (IDCATEGORIEPLACE),
    CONSTRAINT FK_VD_REMISE FOREIGN KEY (IDREMISE_APPLIQUEE)
        REFERENCES REMISE (ID)
);

CREATE INDEX IDX_VD_VENTE ON VENTEDETAILS (IDVENTE);

-- Une ligne annulee libere la place; les lignes actives restent uniques par seance/place.
CREATE UNIQUE INDEX UK_VD_SEANCE_PLACE_ACTIF ON VENTEDETAILS (
    CASE WHEN STATUT IN ('BLOQUEE', 'ACHETEE') THEN IDSEANCE END,
    CASE WHEN STATUT IN ('BLOQUEE', 'ACHETEE') THEN IDPLACE END
);

