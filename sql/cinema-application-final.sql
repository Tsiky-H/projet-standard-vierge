-- Une place ne peut etre reservee qu'une fois tant qu'elle est BLOQUEE ou ACHETEE.
-- Les reservations EXPIREE ou ANNULEE liberent la place pour une nouvelle reservation.
CREATE UNIQUE INDEX UK_CINE_RESPR_SEANCE_PLACE ON CINE_RESERVATION_PLACE (
    CASE WHEN STATUT IN ('BLOQUEE', 'ACHETEE') THEN IDSEANCE END,
    CASE WHEN STATUT IN ('BLOQUEE', 'ACHETEE') THEN IDPLACE END
);

CREATE INDEX IDX_CINE_RESPR_DETAIL ON CINE_RESERVATION_PLACE (IDRESERVATION_DETAIL);
CREATE INDEX IDX_CINE_RESPR_SEANCE ON CINE_RESERVATION_PLACE (IDSEANCE);

