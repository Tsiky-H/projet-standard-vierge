-- ============================================================================
-- APPLICATION CINEMA (Oracle) - SQL complet des tables metier
-- A executer APRES sql/framework-base.sql
-- Script metier de reference pour le projet cinema.
-- ETAT est reserve au workflow APJ de FACTURECLIENT et MVTCAISSE;
-- STATUT reste l'etat metier. Les reservations/ventes/paiements sont pilotes
-- par les services metier.
-- ============================================================================
SET DEFINE OFF
SET SQLBLANKLINES ON
WHENEVER SQLERROR EXIT SQL.SQLCODE

-- IMPORTANT : script de creation initiale. Il ne supprime aucune table existante.
-- Ne pas le relancer tel quel sur une base deja initialisee : les CREATE TABLE,
-- CREATE SEQUENCE et INSERT echoueront si les objets/donnees existent deja.

