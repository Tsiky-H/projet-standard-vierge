CREATE TABLE FACTURECLIENT (
    IDFACTURECLIENT      VARCHAR2(20)   NOT NULL,
    NUMERO_FACTURE       VARCHAR2(30)   NOT NULL,
    TYPE_DOCUMENT        VARCHAR2(20)   DEFAULT 'FACTURE' NOT NULL,
    IDFACTURE_ORIGINE    VARCHAR2(20),
    IDCLIENT             VARCHAR2(20),
    DATY                 DATE           DEFAULT SYSDATE NOT NULL,
    STATUT               VARCHAR2(20)   DEFAULT 'BROUILLON' NOT NULL,
    ETAT                 NUMBER(4)      DEFAULT 1 NOT NULL,
    MONTANT_HT           NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    MONTANT_TVA          NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    MONTANT_TTC          NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    CONSTRAINT PK_FACTURECLIENT PRIMARY KEY (IDFACTURECLIENT),
    CONSTRAINT UK_FACTURECLIENT_NUM UNIQUE (NUMERO_FACTURE),
    CONSTRAINT CK_FACT_TYPE CHECK (TYPE_DOCUMENT IN ('FACTURE', 'AVOIR')),
    CONSTRAINT CK_FACT_ORIGINE CHECK (
        (TYPE_DOCUMENT = 'FACTURE' AND IDFACTURE_ORIGINE IS NULL)
        OR (TYPE_DOCUMENT = 'AVOIR' AND IDFACTURE_ORIGINE IS NOT NULL)
    ),
    CONSTRAINT CK_FACT_STATUT CHECK (STATUT IN ('BROUILLON', 'PAYEE', 'ANNULEE', 'REMBOURSEE')),
    CONSTRAINT CK_FACT_MONTANTS CHECK (
        MONTANT_HT >= 0 AND MONTANT_TVA >= 0 AND MONTANT_TTC >= 0 AND MONTANT_TTC = MONTANT_HT + MONTANT_TVA
    ),
    CONSTRAINT FK_FACT_CLIENT FOREIGN KEY (IDCLIENT)
        REFERENCES CLIENT (IDCLIENT),
    CONSTRAINT FK_FACT_ORIGINE FOREIGN KEY (IDFACTURE_ORIGINE)
        REFERENCES FACTURECLIENT (IDFACTURECLIENT)
);

CREATE TABLE FACTURECLIENT_LIGNE (
    IDFACTURECLIENT_LIGNE  VARCHAR2(20)   NOT NULL,
    IDFACTURECLIENT        VARCHAR2(20)   NOT NULL,
    DESIGNATION            VARCHAR2(250)  NOT NULL,
    QUANTITE               NUMBER(10, 2)  NOT NULL,
    PRIX_UNITAIRE          NUMBER(12, 2)  NOT NULL,
    TAUX_TVA               NUMBER(5, 2)   DEFAULT 0 NOT NULL,
    MONTANT_HT             NUMBER(14, 2)  NOT NULL,
    MONTANT_TVA            NUMBER(14, 2)  NOT NULL,
    MONTANT_TTC            NUMBER(14, 2)  NOT NULL,
    IDRESERVATION_PLACE    VARCHAR2(20),
    IDVENTEDETAILS         VARCHAR2(20),
    IDFACTURECLIENT_LIGNE_ORIGINE VARCHAR2(20),
    CONSTRAINT PK_FACTURECLIENT_LIGNE PRIMARY KEY (IDFACTURECLIENT_LIGNE),
    CONSTRAINT CK_FACTL_QTE CHECK (QUANTITE > 0),
    CONSTRAINT CK_FACTL_PRIX CHECK (PRIX_UNITAIRE >= 0),
    CONSTRAINT CK_FACTL_TVA CHECK (TAUX_TVA >= 0),
    CONSTRAINT CK_FACTL_MONTANTS CHECK (
        MONTANT_HT >= 0 AND MONTANT_TVA >= 0 AND MONTANT_TTC >= 0 AND MONTANT_TTC = MONTANT_HT + MONTANT_TVA
    ),
    CONSTRAINT CK_FACTL_SOURCE CHECK (
        (IDFACTURECLIENT_LIGNE_ORIGINE IS NOT NULL AND IDRESERVATION_PLACE IS NULL AND IDVENTEDETAILS IS NULL)
        OR (IDFACTURECLIENT_LIGNE_ORIGINE IS NULL AND
            ((IDRESERVATION_PLACE IS NOT NULL AND IDVENTEDETAILS IS NULL)
             OR (IDRESERVATION_PLACE IS NULL AND IDVENTEDETAILS IS NOT NULL)))
    ),
    CONSTRAINT FK_FACTL_FACT FOREIGN KEY (IDFACTURECLIENT)
        REFERENCES FACTURECLIENT (IDFACTURECLIENT),
    CONSTRAINT FK_FACTL_RESPR FOREIGN KEY (IDRESERVATION_PLACE)
        REFERENCES CINE_RESERVATION_PLACE (IDRESERVATION_PLACE),
    CONSTRAINT FK_FACTL_ORIGINE FOREIGN KEY (IDFACTURECLIENT_LIGNE_ORIGINE)
        REFERENCES FACTURECLIENT_LIGNE (IDFACTURECLIENT_LIGNE)
);

CREATE INDEX IDX_FACTL_FACTURE ON FACTURECLIENT_LIGNE (IDFACTURECLIENT);

