-- IMPORTANT : script de creation initiale. Il ne supprime aucune table existante.
-- Ne pas le relancer tel quel sur une base deja initialisee : les CREATE TABLE
-- et CREATE SEQUENCE echoueront si les objets existent deja.
-- Les insertions sont dans sql/cinema-application-data.sql.

-- ============================================================================
-- 1) Tables de reference commerciale
-- ============================================================================
CREATE TABLE CLIENT (
    IDCLIENT            VARCHAR2(20)   NOT NULL,
    NOM                 VARCHAR2(80)   NOT NULL,
    PRENOM              VARCHAR2(80),
    EMAIL               VARCHAR2(120),
    TELEPHONE           VARCHAR2(30),
    ACTIF               NUMBER(1)      DEFAULT 1 NOT NULL,
    DATYCREATION        DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_CLIENT PRIMARY KEY (IDCLIENT),
    CONSTRAINT CK_CLIENT_ACTIF CHECK (ACTIF IN (0, 1))
);

CREATE TABLE MODEPAIEMENT (
    IDMODEPAIEMENT      VARCHAR2(20)   NOT NULL,
    LIBELLE             VARCHAR2(100)  NOT NULL,
    ACTIF               NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT PK_MODEPAIEMENT PRIMARY KEY (IDMODEPAIEMENT),
    CONSTRAINT CK_MODEPAIEMENT_ACTIF CHECK (ACTIF IN (0, 1))
);

CREATE TABLE CAISSE (
    IDCAISSE            VARCHAR2(20)   NOT NULL,
    LIBELLE             VARCHAR2(100)  NOT NULL,
    SOLDE_THEORIQUE     NUMBER(14, 2)  DEFAULT 0 NOT NULL,
    ACTIF               NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CAISSE PRIMARY KEY (IDCAISSE),
    CONSTRAINT CK_CAISSE_ACTIF CHECK (ACTIF IN (0, 1))
);

-- ============================================================================
-- 2) Tables cinema (referentiel + planification)
-- ============================================================================
CREATE TABLE CINE_CATEGORIE_PLACE (
    IDCATEGORIEPLACE    VARCHAR2(20)   NOT NULL,
    LIBELLE             VARCHAR2(80)   NOT NULL,
    PRIX_BASE           NUMBER(12, 2)  NOT NULL,
    ACTIF               NUMBER(1)      DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CINE_CATEGORIE_PLACE PRIMARY KEY (IDCATEGORIEPLACE),
    CONSTRAINT CK_CINE_CAT_PRIX CHECK (PRIX_BASE >= 0),
    CONSTRAINT CK_CINE_CAT_ACTIF CHECK (ACTIF IN (0, 1))
);

CREATE TABLE REMISE (
    ID                  VARCHAR2(20)   NOT NULL,
    CAT_RESERVEE        VARCHAR2(20)   NOT NULL,
    NOMBRE              NUMBER(5)      NOT NULL,
    VAL                 NUMBER(5, 2)   NOT NULL,
    CAT_REMISE          VARCHAR2(20)   NOT NULL,
    CONSTRAINT PK_REMISE PRIMARY KEY (ID),
    CONSTRAINT UK_REMISE_CATEGORIE UNIQUE (CAT_RESERVEE, NOMBRE, CAT_REMISE),
    CONSTRAINT CK_REMISE_NOMBRE CHECK (NOMBRE > 0),
    CONSTRAINT CK_REMISE_VAL CHECK (VAL > 0 AND VAL <= 100),
    CONSTRAINT CK_REMISE_CATEGORIES CHECK (CAT_RESERVEE <> CAT_REMISE),
    CONSTRAINT FK_REMISE_CAT_RES FOREIGN KEY (CAT_RESERVEE)
        REFERENCES CINE_CATEGORIE_PLACE (IDCATEGORIEPLACE),
    CONSTRAINT FK_REMISE_CAT_REM FOREIGN KEY (CAT_REMISE)
        REFERENCES CINE_CATEGORIE_PLACE (IDCATEGORIEPLACE)
);

CREATE TABLE CINE_SALLE (
    IDSALLE             VARCHAR2(20)   NOT NULL,
