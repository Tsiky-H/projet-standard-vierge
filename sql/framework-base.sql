-- 5. VUES (2)
-- LISTECOLONNETABLE : metadonnees des colonnes lues par le framework (ListeColonneTable).
-- UTILISATEURVALIDE : utilisateurs actifs avec leur rang (UtilisateurUtil).
-- ============================================================================
CREATE OR REPLACE FORCE VIEW "LISTECOLONNETABLE" ("OWNER","TABLE_NAME","COLUMN_NAME","DATA_TYPE","DATA_TYPE_MOD","DATA_TYPE_OWNER","DATA_LENGTH","DATA_PRECISION","DATA_SCALE","NULLABLE","COLUMN_ID","DEFAULT_LENGTH","DATA_DEFAULT","NUM_DISTINCT","LOW_VALUE","HIGH_VALUE","DENSITY","NUM_NULLS","NUM_BUCKETS","LAST_ANALYZED","SAMPLE_SIZE","CHARACTER_SET_NAME","CHAR_COL_DECL_LENGTH","GLOBAL_STATS","USER_STATS","AVG_COL_LEN","CHAR_LENGTH","CHAR_USED","V80_FMT_IMAGE","DATA_UPGRADED","HISTOGRAM") AS
select 'a' as owner , ua."TABLE_NAME",ua."COLUMN_NAME",ua."DATA_TYPE",ua."DATA_TYPE_MOD",ua."DATA_TYPE_OWNER",ua."DATA_LENGTH",ua."DATA_PRECISION",ua."DATA_SCALE",ua."NULLABLE",ua."COLUMN_ID",ua."DEFAULT_LENGTH",ua."DATA_DEFAULT",ua."NUM_DISTINCT",ua."LOW_VALUE",ua."HIGH_VALUE",ua."DENSITY",ua."NUM_NULLS",ua."NUM_BUCKETS",ua."LAST_ANALYZED",ua."SAMPLE_SIZE",ua."CHARACTER_SET_NAME",ua."CHAR_COL_DECL_LENGTH",ua."GLOBAL_STATS",ua."USER_STATS",ua."AVG_COL_LEN",ua."CHAR_LENGTH",ua."CHAR_USED",ua."V80_FMT_IMAGE",ua."DATA_UPGRADED",ua."HISTOGRAM" from USER_TAB_COLUMNS ua union all
select tc.OWNER,syn.SYNONYM_NAME as table_name, tc.COLUMN_NAME,tc.DATA_TYPE,tc.DATA_TYPE_MOD,
       tc.DATA_TYPE_OWNER,tc.DATA_LENGTH,tc.DATA_PRECISION,tc.DATA_SCALE,tc.NULLABLE,tc.COLUMN_ID,
       tc.DEFAULT_LENGTH,tc.DATA_DEFAULT,tc.NUM_DISTINCT,tc.LOW_VALUE,tc.HIGH_VALUE,tc.DENSITY,
       tc.NUM_NULLS,tc.NUM_BUCKETS,tc.LAST_ANALYZED,tc.SAMPLE_SIZE,tc.CHARACTER_SET_NAME,
       tc.CHAR_COL_DECL_LENGTH,
       tc.GLOBAL_STATS,tc.USER_STATS,tc.AVG_COL_LEN,tc.CHAR_LENGTH,tc.CHAR_USED,tc.V80_FMT_IMAGE,
       tc.DATA_UPGRADED,tc.HISTOGRAM
from ALL_TAB_COLUMNS tc join USER_SYNONYMS syn on syn.TABLE_NAME=tc.TABLE_NAME and syn.TABLE_OWNER=tc.OWNER
;

CREATE OR REPLACE FORCE VIEW "UTILISATEURVALIDE" ("REFUSER","LOGINUSER","PWDUSER","NOMUSER","ADRUSER","TELUSER","IDROLE","RANG") AS
SELECT u.REFUSER, u.LOGINUSER, u.PWDUSER, u.NOMUSER, u.ADRUSER, u.TELUSER,
       u.IDROLE,r.RANG
FROM utilisateur u ,ROLES r , annulationutilisateur a
WHERE u.IDROLE = r.IDROLE and
    u.refuser = a.REFUSER(+) and a.REFUSER is null
